"""Compiling a user's function (UDF) on UDTs into a GraphBLAS operator.

GraphBLAS calls an operator as a C function on pointers to raw elements. A UDF
written for a record or array UDT takes Numba records and arrays instead, and
may return a tuple, an array or a number to fill the result's element. The
functions here generate the Numba cfunc between the two: it reads each operand
through its pointer, calls the UDF, and writes what it returns into the output
element. A return that cannot fill that element is an error when the op is
typed, not inside the cfunc. ``_finalize_udt_op`` then registers the cfunc as
a GraphBLAS operator.

Built-in operators that lift to UDTs are generated by ``udt_codegen``, which uses
these too. ``_bool_to_int8``, the numba#5395 workaround, is here as well: every
Numba UDF on BOOL uses it, not only those on UDTs. So is ``_compile_for_dtype``,
which every UDF's per-dtype build uses.

Importing this module needs Numba.
"""

import re
import warnings

import numba
import numpy as np
from numba import NumbaError
from numba.core.errors import LoweringError, NumbaPendingDeprecationWarning

from ...dtypes import BOOL, INT8, UINT64, lookup_dtype
from ...exceptions import UdfParseError, check_status_carg
from .. import ffi, lib
from ..dtypes import _sample_values
from ..udt import _iter_record_leaves
from .base import _GB_OBJ_C_TYPENAME
from .udt_codegen import _compile_codegen


def _bool_to_int8(dtype):
    """Return INT8 if ``dtype`` is BOOL, else the dtype unchanged.

    Numba can't compile cfuncs that read or write ``CPointer(boolean)``
    (errors like ``cannot store i1 to i8*`` / ``cond is not i1: i8``); see
    numba/numba#5395. Routing BOOL through INT8 sidesteps that; GraphBLAS
    coerces back at the cfunc boundary.

    MAINT 2026-10-18: still hits on Numba 0.68. Re-test periodically and
    drop the INT8 routing when upstream is fixed.
    """
    return INT8 if dtype == BOOL else dtype


def _numba_compile(numba_func, sig):
    """``numba_func.compile(sig)``, without Numba's warning about how it captures errors.

    Numba before 0.60 captures errors "old_style" by default: a bare exception
    from lowering, such as the NotImplementedError for an op Numba types but
    cannot lower, comes out as a LoweringError raised from it. 0.58 and 0.59
    also warn NumbaPendingDeprecationWarning that code may depend on this, and
    ``-W error`` (as in our tests) raises that warning instead of the error.
    The callers here handle both styles, so the warning only gets in the way.
    """
    # MAINT 2026-10-28: once Numba 0.61 is the minimum (0.60 made "new_style" the
    # default; 0.61 removed "old_style"), drop this warning filter and the
    # LoweringError branch in _compile_for_dtype.
    if getattr(numba.core.config, "CAPTURED_ERRORS", None) != "old_style":
        numba_func.compile(sig)
        return
    with warnings.catch_warnings():
        warnings.filterwarnings(
            "ignore",
            "Code using Numba extension API maybe depending on 'old_style'",
            NumbaPendingDeprecationWarning,
        )
        numba_func.compile(sig)


def _compile_for_dtype(numba_func, sig):
    """Compile ``sig`` and return whether Numba could; raise any other error.

    It cannot when the function does not type for ``sig``, or when Numba types
    an op it has no lowering for, such as ``>`` (so ``max``) on complex values.
    Numba raises a bare NotImplementedError for the latter, or before 0.60 a
    LoweringError from one.
    """
    try:
        _numba_compile(numba_func, sig)
    except (numba.TypingError, NotImplementedError):
        return False
    except LoweringError as exc:
        if isinstance(exc.__context__, NotImplementedError):
            return False
        raise
    return True


def _finalize_udt_op(parent_op, dtype, dtype2, ret_type, wrapper, wrapper_sig, typed_user_cls):
    """Compile the cfunc, allocate the ``GrB`` op, wrap it, and cache it.

    Shared tail for ``_compile_udt`` in UnaryOp / BinaryOp / IndexUnaryOp /
    SelectOp. Looks up the SuiteSparse handle type and ``_new`` symbol
    from ``typed_user_cls.opclass``. ``dtype2`` is ``None`` for unary
    ops; the rest pass both. Returns the cached ``TypedUser*Op``.
    """
    try:
        wrapper = numba.cfunc(wrapper_sig, nopython=True, error_model="numpy")(wrapper)
    except NumbaError as exc:
        dtypes_str = str(dtype) if dtype2 is None else f"{dtype}, {dtype2}"
        raise UdfParseError(
            f"{parent_op._modname}.{parent_op.name} does not work with ({dtypes_str}): "
            f"{_summarize_numba_typing_error(exc)}"
        ) from exc
    c_typename = _GB_OBJ_C_TYPENAME[typed_user_cls.opclass]
    error_label = c_typename.removeprefix("GrB_").removeprefix("GxB_")
    gb_obj = ffi.new(f"{c_typename}*")
    new_func = getattr(lib, f"{c_typename}_new")
    if dtype2 is None:
        check_status_carg(
            new_func(gb_obj, wrapper.cffi, ret_type._carg, dtype._carg),
            error_label,
            gb_obj[0],
        )
        op = typed_user_cls(parent_op, parent_op.name, dtype, ret_type, gb_obj[0])
        key = dtype
    else:
        check_status_carg(
            new_func(gb_obj, wrapper.cffi, ret_type._carg, dtype._carg, dtype2._carg),
            error_label,
            gb_obj[0],
        )
        op = typed_user_cls(parent_op, parent_op.name, dtype, ret_type, gb_obj[0], dtype2=dtype2)
        key = (dtype, dtype2)
    parent_op._udt_types[key] = ret_type
    parent_op._udt_ops[key] = op
    return op


def _compile_udf_for_udt(numba_func, sig, *, op_kind, op_name, dtypes):
    """Compile ``sig`` and re-raise Numba compilation errors as ``UdfParseError``.

    Catches the full ``NumbaError`` hierarchy (TypingError, LoweringError,
    UnsupportedError, ...) so any compilation failure produces a
    single-line UDT diagnostic. Also catches the bare NotImplementedError
    Numba raises for an op it types but cannot lower, such as ``>`` (so
    ``max``) on complex values.
    """
    try:
        _numba_compile(numba_func, sig)
    except (NumbaError, NotImplementedError) as exc:
        dtypes_str = ", ".join(str(d) for d in dtypes)
        snippet = _summarize_numba_typing_error(exc)
        raise UdfParseError(
            f"{op_kind}.{op_name} does not work with ({dtypes_str}): {snippet}"
        ) from exc


# Numba prefixes its actionable diagnostic line with one of these.
_NUMBA_DIAG_PREFIXES = (
    "No implementation of function",
    "No definition for lowering",
    "No conversion from",
    "Field ",
    "Cannot infer",
    "Operator Overload",
    "Invalid use of",
    "use of undeclared",
    "Untyped global",
)

_ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")


def _summarize_numba_typing_error(exc):
    """Pull the most actionable lines out of a Numba TypingError.

    Numba's "No implementation of function ... found for signature:"
    diagnostic puts the signature on the line *below* the prefix; the
    signature is the actionable part. When the matched line ends with a
    ``:``, append the next non-empty line so the user sees both.
    """
    lines = [_ANSI_RE.sub("", line).strip() for line in str(exc).splitlines()]
    for i, line in enumerate(lines):
        if line.startswith(_NUMBA_DIAG_PREFIXES):
            if line.endswith(":"):
                for follow in lines[i + 1 :]:
                    if follow:
                        return f"{line} {follow}"
            return line
    for line in lines:
        if line:
            return line
    return "Numba could not compile the function for these input types"


def _array_udt_operands(dtypes):
    """Return the distinct array-UDT operands in ``dtypes``, order preserved.

    ``x`` and ``y`` are usually the same UDT, hence the dedup.
    """
    operands = []
    for d in dtypes:
        if d._is_udt and d.np_type.subdtype is not None and not any(d is seen for seen in operands):
            operands.append(d)
    return operands


def _udt_ret_type(parent_op, numba_ret_type, *dtypes):
    """Return the operator's declared ``ret_dtype``, else infer one from the UDF.

    Inference can only name a type that is already an operand, so an output
    UDT that appears nowhere in the inputs is unreachable without this.
    """
    if (ret_dtype := parent_op._ret_dtype) is not None:
        return ret_dtype
    return _resolve_udt_return_type(numba_ret_type, *dtypes)


def _resolve_udt_return_type(numba_ret_type, *dtypes):
    """Resolve a Numba return type to a DataType, matching Tuple returns to an input UDT.

    When a UDF returns a tuple, Numba infers ``Tuple(...)`` rather than a
    Record type. Match by field count, preferring a candidate whose field
    types align with the Tuple's element types. An array the UDF builds
    (``x + y``) is typed without its extents, so it takes the type of the
    array-UDT operand with the same element type and rank.
    """
    try:
        return lookup_dtype(numba_ret_type)
    except (ValueError, TypeError):
        pass
    for d in dtypes:
        # Bytes and the like have a Numba type no DataType is registered for;
        # an operand of that type, returned as it is, keeps its UDT.
        if (
            d._is_udt
            and d.np_type.names is None
            and d.np_type.subdtype is None
            and d.numba_type == numba_ret_type
        ):
            return d
    if isinstance(numba_ret_type, numba.core.types.BaseTuple):
        n = len(numba_ret_type.types)

        def _leaves(d):
            """Return ``(python_path, c_path, leaf_dtype)`` for each leaf of a record UDT."""
            return list(_iter_record_leaves(d.np_type))

        # Match by total leaf count (flat for shallow records, total
        # leaves across nesting for nested records).
        same_arity = [
            d for d in dtypes if d._is_udt and d.np_type.names is not None and len(_leaves(d)) == n
        ]
        # Prefer a UDT whose leaf types match the tuple elements element-wise.
        for d in same_arity:
            leaf_dtypes = [leaf for _py, _c, leaf in _leaves(d)]
            try:
                expected = [lookup_dtype(t).numba_type for t in leaf_dtypes]
            except (ValueError, TypeError):  # pragma: no cover (safety)
                continue  # no record UDT has such a leaf: a void field fails to register
            if all(et == tt for et, tt in zip(expected, numba_ret_type.types, strict=True)):
                return d
        # No perfect match; fall back to the first arity-compatible UDT.
        if same_arity:
            return same_arity[0]
        # Tuple return whose arity matches no input UDT: most likely the
        # user is returning the wrong number of fields. List the candidate
        # arities so the fix is obvious.
        record_arities = sorted(
            {len(_leaves(d)) for d in dtypes if d._is_udt and d.np_type.names is not None}
        )
        if record_arities:
            expected = " or ".join(str(a) for a in record_arities)
            raise UdfParseError(
                f"UDT UDF returned a tuple of length {n}; expected {expected} "
                f"to match one of the input record UDTs."
            )
        # All UDT inputs are array UDTs. Tuples don't map to those: the
        # function should return a numpy array of the right shape (or a
        # scalar) instead.
        array_inputs = [d for d in dtypes if d._is_udt and d.np_type.subdtype is not None]
        if array_inputs:
            shape = array_inputs[0].np_type.subdtype[1]
            raise UdfParseError(
                f"UDT UDF returned a tuple of length {n}, but inputs are array UDTs of "
                f"shape {shape}. Return a numpy array (e.g., ``np.array(...)``) or a "
                f"scalar; tuple returns are only matched to record UDTs."
            )
    elif isinstance(numba_ret_type, numba.core.types.Array):
        # Numba types an array the UDF builds as a plain ``Array``: element
        # type and rank, but no extents, which only an operand can supply.
        # (An operand returned as-is keeps its ``NestedArray`` type, extents
        # and all, and ``lookup_dtype`` resolved it above.)
        array_inputs = list(
            dict.fromkeys(  # dedup: ``x`` and ``y`` are often the same UDT
                d for d in dtypes if d._is_udt and d.np_type.subdtype is not None
            )
        )
        if isinstance(numba_ret_type, numba.core.types.NestedArray):
            # Extents survived, so ``lookup_dtype`` above named a UDT for
            # them unless SuiteSparse refused to create it: builds without
            # variable-length arrays cap a UDT at 128 bytes before SS 9.0
            # and 1024 from then on. Matching those extents to a same-rank
            # operand would hand SuiteSparse an element of the wrong size.
            shaped_like = []
        else:
            shaped_like = [
                d
                for d in array_inputs
                if d.numba_type.dtype == numba_ret_type.dtype
                and d.numba_type.ndim == numba_ret_type.ndim
            ]
        if len(shaped_like) == 1:
            return shaped_like[0]
        if shaped_like:
            # Operands that differ only in length are indistinguishable
            # here. Guessing would hand SuiteSparse an element of the
            # wrong size, so say so.
            raise UdfParseError(
                f"UDT UDF returned {numba_ret_type!r}, which matches more than one "
                f"input array UDT ({', '.join(str(d) for d in shaped_like)}). "
                f"Return one of the operands, or make the operands the same type."
            )
        # An array UDT went in and an array came out, but not one that
        # fits: name the mismatch rather than fall through to the generic
        # "unsupported type", whose advice the user already followed.
        if array_inputs:
            described = "; ".join(
                f"{d} elements are {d.numba_type.dtype} with shape {d.numba_type.shape}"
                for d in array_inputs
            )
            raise UdfParseError(
                f"UDT UDF returned {numba_ret_type!r}, which matches no input array "
                f"UDT: {described}. Return an array matching one of those, or one of "
                f"the operands."
            )
    raise UdfParseError(
        f"UDT UDF returned an unsupported type {numba_ret_type!r}. "
        f"Return a scalar, a tuple matching a record UDT's fields, or a numpy array "
        f"matching an array UDT's shape."
    )


def _array_udt_view(dtype):
    """Return ``(base_element_numba_type, shape)`` for an array UDT.

    Array UDTs are addressed as a ``carray`` over their base elements, in
    the UDT's declared shape, rather than as Numba's ``NestedArray``. Numba
    models a ``NestedArray`` *value* as an array descriptor (data pointer,
    shape, strides, ...), so loading or storing one through a ``CPointer``
    moves the descriptor rather than the element payload, corrupting
    whatever follows it (and overrunning the element outright once the
    descriptor is the wider of the two).
    """
    nested = dtype.numba_type
    return nested.dtype, nested.shape


def _input_operand(dtype, var):
    """Return ``(setup_line, deref_expr, ptr_arg_type)`` for one input operand.

    - ``setup_line`` is the optional ``var = numba.carray(var_ptr, n)`` line
      to add to the wrapper body, where ``n`` is 1 for a record UDT and the
      element's shape for an array UDT (empty for non-UDT cases).
    - ``deref_expr`` is the value to pass to ``numba_func`` for this operand.
    - ``ptr_arg_type`` is the Numba ``CPointer(...)`` type for the wrapper signature.
    """
    nt = numba.types
    if dtype._is_udt:
        if dtype.np_type.subdtype is None:
            return (
                f"    {var} = numba.carray({var}_ptr, 1)\n",
                f"{var}[0]",
                nt.CPointer(dtype.numba_type),
            )
        base_numba, shape = _array_udt_view(dtype)
        return (
            f"    {var} = numba.carray({var}_ptr, {shape})\n",
            var,
            nt.CPointer(base_numba),
        )
    if dtype == BOOL:
        # Numba can't compile bool ptrs (numba/numba#5395); expose them
        # as int8 and cast on deref.
        # MAINT 2026-10-18: still hits on Numba 0.68; re-test periodically.
        return "", f"bool({var}_ptr[0])", nt.CPointer(INT8.numba_type)
    return "", f"{var}_ptr[0]", nt.CPointer(dtype.numba_type)


def _output_handler(return_type, numba_ret_type):
    """Return ``(setup_line, ret_ptr_type, write_kind, write_info)``.

    ``write_kind`` is ``"record_fields"`` when the UDF returns a Tuple to be
    unpacked into a record output, ``"array_elements"`` for an array UDT
    output, otherwise ``"direct"``. ``write_info`` is one
    ``(access_path, is_array)`` pair per leaf for ``"record_fields"`` and a
    ``(BL, BR, zname)`` 3-tuple for ``"direct"``; ``"array_elements"`` needs
    none, since ``setup_line`` already binds ``z`` to the right shape.
    """
    nt = numba.types
    ztype = INT8 if return_type == BOOL else return_type
    ret_ptr_type = nt.CPointer(ztype.numba_type)

    if (
        numba_ret_type is not None
        and isinstance(numba_ret_type, numba.core.types.BaseTuple)
        and return_type._is_udt
        and return_type.np_type.names is not None
    ):
        # ``write_info`` pairs each leaf field's Python access path
        # (``"['a']"`` for flat, ``"['outer']['inner_a']"`` for nested)
        # with whether that leaf is array-typed. The wrapper iterates
        # these to write the flat tuple ``_result`` back leaf-by-leaf.
        leaves = tuple(
            (py, d.subdtype is not None) for py, _c, d in _iter_record_leaves(return_type.np_type)
        )
        return (
            "    z = numba.carray(z_ptr, 1)\n",
            ret_ptr_type,
            "record_fields",
            leaves,
        )
    if return_type._is_udt:
        if return_type.np_type.subdtype is None:
            return (
                "    z = numba.carray(z_ptr, 1)\n",
                ret_ptr_type,
                "direct",
                ("", "", "z[0]"),
            )
        base_numba, shape = _array_udt_view(return_type)
        return (
            f"    z = numba.carray(z_ptr, {shape})\n",
            nt.CPointer(base_numba),
            "array_elements",
            None,
        )
    if return_type == BOOL:
        return "", ret_ptr_type, "direct", ("bool(", ")", "z_ptr[0]")
    return "", ret_ptr_type, "direct", ("", "", "z_ptr[0]")


def _compose_wrapper_body(zkind, zinfo, signature_line, body_setup, call_expr):
    """Assemble the Python source for a UDT cfunc wrapper.

    For record returns, the wrapper writes leaf-by-leaf; Numba does not
    compile a nested-tuple assignment to an outer record field. Array
    returns and array-typed record leaves slice-assign into the caller's
    buffer, so a wrong-shape return cannot overrun it. The error does not reach
    the caller either: the resulting ``ValueError`` is raised inside a
    cfunc, which Numba prints and swallows, so the write stops there and
    every leaf from that point on keeps whatever SuiteSparse had in the
    buffer. :func:`_check_udf_fills_output` rejects such a return when the
    op is typed, but it cannot always learn the shape, so this stays the
    backstop.
    """
    if zkind == "array_elements":
        return (
            f"{signature_line}\n"
            f"{body_setup}"
            f"    _result = {call_expr}\n"
            f"    z[:] = _result\n"
        )
    if zkind == "record_fields":
        # Array-typed leaves slice-assign. Numba's record-field setitem
        # copies the destination's extent regardless of the source's, so a
        # short source is read past its end and a long one is silently
        # truncated; ``[:]`` makes both a shape error instead.
        field_assigns = "".join(
            f"    z[0]{path}{'[:]' if is_array else ''} = _result[{i}]\n"
            for i, (path, is_array) in enumerate(zinfo)
        )
        return f"{signature_line}\n{body_setup}    _result = {call_expr}\n{field_assigns}"
    BL, BR, zname = zinfo
    return f"{signature_line}\n{body_setup}    {zname} = {BL}{call_expr}{BR}\n"


def _fits_by_broadcast(shape, expected):
    """Whether a return of ``shape`` fills an ``expected``-shaped destination.

    The wrapper slice-assigns (``z[:] = ...``), and numpy broadcasts on
    assignment, so an exact match is not the requirement: a ``(1,)`` return
    legitimately fills a ``(6,)`` element, and a ``(1, 3)`` return fills
    every row of a ``(2, 3)`` one. Rejecting those would refuse code that
    works today.

    numpy's assignment rule is broadcasting plus a leading-``1`` strip when
    the source has the higher rank, so ``(1, 6)`` fits ``(6,)`` while
    ``(6, 1)`` does not. ``test_udt_broadcast_matches_numba_slice_assign``
    pins this against Numba's own slice-assign for both.
    """
    shape = tuple(shape)
    expected = tuple(expected)
    while len(shape) > len(expected) and shape[0] == 1:
        shape = shape[1:]
    try:
        return np.broadcast_shapes(shape, expected) == expected
    except ValueError:
        return False


def _udf_probe_value(dtype):
    """Build a stand-in operand of ``dtype`` for :func:`_run_udf_probe`.

    Only the shape of the UDF's result is read, so any values it accepts
    will do.
    """
    if dtype._is_udt:
        np_type = dtype.np_type
        if np_type.subdtype is None:
            return np.ones(1, dtype=np_type)[0]
        base_np_type, shape = np_type.subdtype
        return np.ones(shape, dtype=base_np_type)
    return _sample_values[dtype]


def _run_udf_probe(numba_func, arg_dtypes):
    """Call the UDF on stand-in operands. Returns ``(result,)``, or ``None`` if it raised.

    A UDF that raises on the stand-in values is not checked, so one that
    also returns a shape that does not fit is left to the wrapper, which
    fails without telling the caller (see :func:`_compose_wrapper_body`).
    Only the call is guarded, so a mistake in building the operands still
    surfaces.

    This is where typing an op for a UDT runs the user's function rather
    than only compiling it, and ``OpBase.__contains__`` is a typed lookup,
    so ``udt in some_op`` can run it too. It costs no extra compile: Numba
    types the stand-ins as it types the wrapper's operands (a C-contiguous
    array, a record, a scalar), so the call compiles the specialization the
    wrapper needs anyway.
    """
    args = [_udf_probe_value(d) for d in arg_dtypes]
    try:
        return (numba_func(*args),)
    except NumbaError as exc:  # pragma: no cover (safety)
        # The wrapper's operands have these types, so it would fail to compile too.
        raise UdfParseError(_summarize_numba_typing_error(exc)) from exc
    except Exception:
        return None


def _raise_unless_fits(shape, expected, return_type, path, *, probed):
    """Raise ``UdfParseError`` unless a return of ``shape`` fills an ``expected`` slot.

    ``path`` is the record field, or ``None`` for an array UDT's element.
    """
    if _fits_by_broadcast(shape, expected):
        return
    field = "" if path is None else f" for field {path} of {return_type}"
    # A probed shape holds for the values the probe used. Saying so helps
    # the author of a UDF whose output shape depends on its inputs' values.
    how = " when run on sample values" if probed else ""
    slot = f"{return_type} elements are" if path is None else "that field holds"
    raise UdfParseError(
        f"UDT UDF returned an array of shape {tuple(shape)}{field}{how}, but {slot} "
        f"{tuple(expected)}. Return an array of that shape, or one that broadcasts to it."
    )


def _raise_unless_sequence_fits(kind, length, expected, return_type, path, *, probed):
    """Raise ``UdfParseError`` unless a ``kind`` of ``length`` fills record field ``path``.

    Numba copies a tuple or list into an array field element by element,
    which works only for a one-dimensional field and only at its exact
    length. Unlike an array, a sequence does not broadcast, so a 1-tuple
    does not fill a 3-element field. A wrong length raises inside the cfunc
    just as a wrong-shape array does; a field of higher rank fails the
    wrapper compile.
    """
    if expected == (length,):
        return
    how = " when run on sample values" if probed else ""
    if len(expected) == 1:
        fix = f"Return {expected[0]} values, or an array that broadcasts to {expected}."
    else:
        fix = f"A {kind} only fills a one-dimensional field; return an array."
    raise UdfParseError(
        f"UDT UDF returned a {kind} of length {length} for field {path} of {return_type}"
        f"{how}, but that field holds {expected}. {fix}"
    )


# Numba types a record UDF might return for a scalar field, none of which the
# wrapper can write there, each with the kind the error names. ``Array``
# covers ``NestedArray``.
_NON_SCALAR_KINDS = (
    ("an array", numba.core.types.Array),
    ("a tuple", numba.core.types.BaseTuple),
    ("a list", numba.core.types.List),
)


def _check_udf_fills_output(numba_func, numba_ret_type, return_type, zkind, arg_dtypes):
    """Reject a UDF whose return cannot fill the output element.

    The wrapper slice-assigns an array return, and each array-typed record
    leaf, into the element, so a shape that does not fit raises inside the
    cfunc, where the caller never sees it (see
    :func:`_compose_wrapper_body`). So does a record leaf the UDF can
    return as ``None`` (``v if cond else None``, typed ``Optional``), array
    or scalar, on the path that returns it; a leaf that is always ``None``
    does not compile at all, and Numba's traceback says why at length. Nor
    does an array, tuple or list returned for a scalar leaf: Numba has no
    record setitem for them. Checking here makes each an error when the op
    is typed.

    An ``Optional`` leaf is rejected from its type, whichever branch the
    sample values would take. Numba also keeps the extents of an operand,
    or operand field, returned as-is (a ``NestedArray``), so those are
    checked from the type alone. An array the UDF builds (``x + y``,
    ``x[:2]``) is a plain ``Array``, which has a rank but no extents, so
    only running the UDF, on stand-ins built from ``arg_dtypes``, can say
    what shape it has. A tuple or list for an array leaf must match its
    length exactly (:func:`_raise_unless_sequence_fits`); a tuple's length
    is in its type, and a list's is learned the same way as a built
    array's. A UDF that returns no built array or list is never run.
    """
    if zkind == "array_elements":
        # (record field path, Numba type, slot shape, index into the tuple)
        slots = [(None, numba_ret_type, return_type.np_type.shape, None)]
    elif zkind == "record_fields":
        # The tuple is flat over the leaves, one element per leaf.
        leaves = list(_iter_record_leaves(return_type.np_type))
        if len(numba_ret_type.types) != len(leaves):
            # _resolve_udt_return_type matched the record to the tuple's length,
            # so this would be a wrong field count, not a wrong shape.
            return  # pragma: no cover (safety)
        slots = [
            (path, numba_ret_type.types[i], leaf.shape, i)
            for i, (path, _c, leaf) in enumerate(leaves)
        ]
    else:
        return
    unknown = []
    for path, nb_type, expected, i in slots:
        if isinstance(nb_type, (numba.core.types.Optional, numba.core.types.NoneType)):
            field = "" if path is None else f" for field {path}"
            raise UdfParseError(
                f"UDT UDF can return None{field}, but {return_type} cannot hold None. "
                f"Return a value on every path."
            )
        if not expected:
            for kind, cls in _NON_SCALAR_KINDS:
                if isinstance(nb_type, cls):
                    raise UdfParseError(
                        f"UDT UDF returned {kind} for field {path} of {return_type}, but "
                        f"that field holds a scalar. Return a scalar for it."
                    )
            continue  # a scalar leaf: nothing to fit
        if isinstance(nb_type, numba.core.types.NestedArray):
            _raise_unless_fits(nb_type.shape, expected, return_type, path, probed=False)
        elif isinstance(nb_type, numba.core.types.Array) or nb_type is None:
            # No extents to read (or, with no return type given, no type
            # at all), so learn the shape by running the UDF.
            unknown.append((path, expected, i))
        elif isinstance(nb_type, numba.core.types.BaseTuple):
            _raise_unless_sequence_fits(
                "tuple", len(nb_type.types), expected, return_type, path, probed=False
            )
        elif isinstance(nb_type, numba.core.types.List):
            unknown.append((path, expected, i))  # a list's length is not in its type
    if unknown and (ran := _run_udf_probe(numba_func, arg_dtypes)) is not None:
        for path, expected, i in unknown:
            value = ran[0] if i is None else ran[0][i]
            if isinstance(value, list):
                _raise_unless_sequence_fits(
                    "list", len(value), expected, return_type, path, probed=True
                )
            else:
                _raise_unless_fits(np.shape(value), expected, return_type, path, probed=True)


def _get_udt_wrapper(
    numba_func, return_type, dtype, dtype2=None, *, include_indexes=False, numba_ret_type=None
):
    """Build a Numba cfunc wrapper for unary, binary, indexunary, or select UDFs on UDTs.

    ``include_indexes=True`` inserts ``(row, col)`` between ``x`` and
    ``y`` in both the wrapper signature and the call to ``numba_func``,
    matching the IndexUnaryOp and SelectOp shape. The IndexBinaryOp path
    (four indices plus a theta operand) uses
    :func:`_get_udt_wrapper_indexbinary`.
    """
    nt = numba.types
    zsetup, zptr_type, zkind, zinfo = _output_handler(return_type, numba_ret_type)
    xsetup, xderef, xptr_type = _input_operand(dtype, "x")
    wrapper_args = [zptr_type, xptr_type]
    arg_dtypes = [dtype]
    if include_indexes:
        wrapper_args.extend([UINT64.numba_type, UINT64.numba_type])
        arg_dtypes.extend([UINT64, UINT64])
    ysetup, yderef_expr, yarg = "", "", ""
    if dtype2 is not None:
        ysetup, yderef, yptr_type = _input_operand(dtype2, "y")
        wrapper_args.append(yptr_type)
        arg_dtypes.append(dtype2)
        yarg = ", y_ptr"
        yderef_expr = f", {yderef}"
    wrapper_sig = nt.void(*wrapper_args)
    _check_udf_fills_output(numba_func, numba_ret_type, return_type, zkind, arg_dtypes)

    rcidx = ", row, col" if include_indexes else ""
    signature_line = f"def wrapper(z_ptr, x_ptr{rcidx}{yarg}):"
    body_setup = f"{zsetup}{xsetup}{ysetup}"
    call_expr = f"numba_func({xderef}{rcidx}{yderef_expr})"

    text = _compose_wrapper_body(zkind, zinfo, signature_line, body_setup, call_expr)
    kind = "indexunary" if include_indexes else ("binary" if dtype2 is not None else "unary")
    wrapper = _compile_codegen(
        text,
        func_name="wrapper",
        source_label=f"<gb-udt-wrapper {kind} dtype={dtype} ret={return_type}>",
        extra_ns={"numba_func": numba_func},
    )
    return wrapper, wrapper_sig


def _get_udt_wrapper_indexbinary(numba_func, return_type, dtype, dtype2, *, numba_ret_type=None):
    """Build a Numba cfunc wrapper for IndexBinaryOp UDFs on UDTs.

    Signature: ``f(x, ix, jx, y, iy, jy, theta) -> z``. ``dtype2`` is the
    shared type of ``y`` and ``theta``.
    """
    nt = numba.types
    zsetup, zptr_type, zkind, zinfo = _output_handler(return_type, numba_ret_type)
    xsetup, xderef, xptr_type = _input_operand(dtype, "x")
    ysetup, yderef, yptr_type = _input_operand(dtype2, "y")
    tsetup, tderef, tptr_type = _input_operand(dtype2, "t")
    wrapper_sig = nt.void(
        zptr_type,
        xptr_type,
        UINT64.numba_type,
        UINT64.numba_type,
        yptr_type,
        UINT64.numba_type,
        UINT64.numba_type,
        tptr_type,
    )
    arg_dtypes = [dtype, UINT64, UINT64, dtype2, UINT64, UINT64, dtype2]
    _check_udf_fills_output(numba_func, numba_ret_type, return_type, zkind, arg_dtypes)

    signature_line = "def wrapper(z_ptr, x_ptr, ix, jx, y_ptr, iy, jy, t_ptr):"
    body_setup = f"{zsetup}{xsetup}{ysetup}{tsetup}"
    call_expr = f"numba_func({xderef}, ix, jx, {yderef}, iy, jy, {tderef})"

    text = _compose_wrapper_body(zkind, zinfo, signature_line, body_setup, call_expr)
    wrapper = _compile_codegen(
        text,
        func_name="wrapper",
        source_label=f"<gb-udt-wrapper indexbinary dtype={dtype} dtype2={dtype2}>",
        extra_ns={"numba_func": numba_func},
    )
    return wrapper, wrapper_sig
